#!/usr/bin/env sh
# Копирует тексты интерфейса из content/i18n во встроенные ресурсы приложения.
# Они нужны только как запасной вариант, пока нет связи с сервером. Запускайте перед выпуском сборки.
set -eu
cd "$(dirname "$0")/.."
mkdir -p assets/i18n
cp ../content/i18n/*.json assets/i18n/
echo "Скопировано файлов: $(ls assets/i18n | wc -l)"
